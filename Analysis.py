import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
df = pd.read_csv("customer_orders.csv")
df = df.dropna()
df["Revenue"] = df["Price"]*df["Quantity"]
print(pd.DataFrame(df))
#Task 1
print("=====Data Overview=====")
print("Total Orders:",np.size(df["Order_ID"]))
print("Total Customers:",len(df["Customer_ID"].unique()))
print("Total Products:",len(df["Product"].unique()))
print("Total Quantity Sold:",np.sum(df["Quantity"]))
print("Total Revenue:",np.sum(df["Revenue"]))
print("First Order Date",np.min(df["Order_Date"]))
print("Last Order Date:",np.max(df["Order_Date"]))
#Task 2
print("=====Customer Performance=====")
a = df.groupby("Customer_ID")["Order_ID"].count()
b = df.groupby("Customer_ID")["Quantity"].sum()
c = df.groupby("Customer_ID")["Revenue"].sum()
print("-----Number of Orders-----")
print(a)
print("-----Total Quantity-----")
print(b)
print("-----Total Revenue-----")
print(c)
print("Highest Revenue Customer:",c.idxmax())
print("Lowest Revenue Customer:",c.idxmin())
print("Highest Quantity Customer:",b.idxmax())
print("Customer with the Most Orders:",a.idxmax())
#Task 3
print("=====Repeat Customers=====")
print("-----Repeat customers-----")
print(a[a>1])
print("Number of repeat customers:",len(a[a>1]))
print("One-time customers:",len(a[a<=1]))
#Task 4
print("=====Product Performance=====")
print("-----Product-wise Revenue-----")
print(df.groupby("Product")["Revenue"].sum())
print("-----Product-wise Quantity-----")
print(df.groupby("Product")["Quantity"].sum())
rev = df.groupby("Product")["Revenue"].sum()
qua = df.groupby("Product")["Quantity"].sum()
print("Best Revenue Product",rev.idxmax())
print("Highest-selling Product:",qua.idxmax())
#Task 5
print("=====Monthly Sales Analysis=====")
df["Order_Date"] = pd.to_datetime(df["Order_Date"])
df["Month"] = df["Order_Date"].dt.strftime("%B")
#print(pd.DataFrame(df))
print("-----Monthly Revenue-----")
print(df.groupby("Month")["Revenue"].sum())
print("-----Monthly Quantity-----")
print(df.groupby("Month")["Quantity"].sum())
print("Best-performing month:",df.loc[df["Revenue"].idxmax(),"Month"])
#Task 6
'''Customer vs Revenue'''
plt.figure(figsize=(8,5))
plt.bar(c.index,c.values)
plt.title("Customer vs Revenue")
plt.xlabel("Customer")
plt.ylabel("Revenue")
plt.show()
'''Product vs Revenue'''
plt.figure(figsize=(8,5))
plt.bar(rev.index,rev.values)
plt.title("Product vs Revenue")
plt.xlabel("Product")
plt.ylabel("Revenue")
plt.show()
'''Month vs Revenue'''
plt.figure(figsize=(8,5))
mon = df.groupby("Month")["Revenue"].sum()
plt.bar(mon.index,mon.values)
plt.title("Month vs Revenue")
plt.xlabel("Month")
plt.ylabel("Revenue")
plt.show()
'''Repeat Customers vs One-time Customers'''
rep = len(a[a>1])
ot = len(a[a == 1])
x = ["Repeat Customers", "One-time Customers"]
y = [rep, ot]
plt.figure(figsize=(8,5))
plt.bar(x, y)
plt.title("Repeat Customers vs One-time Customers")
plt.xlabel("Customer Type")
plt.ylabel("Number of Customers")
plt.show()